"""Theme, budget help and custom categories in an isolated demo instance (8002)."""
import json
import os
import time
from pathlib import Path
from urllib.parse import urlparse
from playwright.sync_api import sync_playwright

BASE = os.environ.get('MARYRUSS_E2E_URL', 'http://127.0.0.1:8002')
address = urlparse(BASE)
if address.hostname not in ('127.0.0.1','localhost') or address.port != 8002:
    raise SystemExit('Usa una instancia demo aislada en el puerto 8002.')
OUTPUT = Path('test-results')
OUTPUT.mkdir(exist_ok=True)
checks, errors = [], []
def check(label, condition):
    assert condition, label
    checks.append(label)

def no_overflow(page):
    return page.evaluate('document.documentElement.scrollWidth <= innerWidth')

with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=os.environ.get('CHROMIUM_PATH','/usr/bin/chromium'), headless=True, args=['--no-sandbox'])
    context = browser.new_context(viewport={'width':1440,'height':1000}, color_scheme='light')
    page = context.new_page()
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(BASE+'/ingresar/')
    select = page.get_by_label('Tema de la aplicación')
    select.select_option('dark')
    check('Modo oscuro en acceso', page.locator('html').get_attribute('data-theme') == 'dark')
    check('Acceso sin superficie blanca', page.locator('.login-form-panel').evaluate('(el)=>getComputedStyle(el).backgroundColor') == 'rgb(27, 38, 33)')
    page.reload()
    check('Preferencia conservada al recargar', page.get_by_label('Tema de la aplicación').input_value() == 'dark')
    page.get_by_role('button', name='Entrar a la demostración').click()
    page.wait_for_url(BASE+'/')
    check('Preferencia conservada al iniciar sesión', page.locator('html').get_attribute('data-theme') == 'dark')
    check('Dashboard en oscuro', page.locator('.metric').first.evaluate('(el)=>getComputedStyle(el).backgroundColor') == 'rgb(27, 38, 33)')
    page.goto(BASE+'/modelos/')
    model_link = page.locator('.model-cell').first
    model_link.click()
    model_url = page.url
    model_path = urlparse(model_url).path
    budget_path = model_path+'costos/nuevo/'
    page.goto(BASE+budget_path)
    check('Todas las entradas de presupuesto con ayuda', page.locator('.field-info summary').count() == 6)
    info = page.locator('.field-info summary').filter(has=page.locator('svg')).first
    info.focus()
    page.keyboard.press('Enter')
    check('Ayuda accesible con teclado', page.locator('.field-info').first.get_attribute('open') is not None)
    page.locator('#id_quantity').fill('1.2')
    page.locator('#id_unit').fill('metro')
    page.locator('#id_unit_price').fill('10')
    units = int(page.locator('[data-budget-units]').get_attribute('data-budget-units'))
    check('Costo por prenda explicado', '12.00' in page.locator('#budget-unit-preview').inner_text())
    check('Fórmula por prenda incluye multiplicación', f'× {units} prendas' in page.locator('#budget-formula').inner_text())
    page.locator('#id_basis').select_option('batch')
    page.locator('#id_quantity').fill('1')
    page.locator('#id_unit').fill('servicio')
    page.locator('#id_unit_price').fill('80')
    check('Costo por lote sin multiplicar por prendas', '80.00' in page.locator('#budget-preview').inner_text())
    check('Indicaciones cambian al elegir lote', page.locator('[data-field-label="quantity"]').inner_text() == 'Cantidad total para este costo')
    check('Fórmula por lote explica distribución', 'Se divide entre' in page.locator('#budget-formula').inner_text())
    page.locator('#id_unit_price').fill('0')
    check('Costo cero permitido en vista previa', '0.00' in page.locator('#budget-preview').inner_text())
    page.locator('#id_unit_price').fill('0.005')
    check('Redondeo medio centavo coincide con servidor', '0.01' in page.locator('#budget-preview').inner_text())
    page.locator('#id_unit_price').fill('')
    check('Vista previa incompleta informativa', 'Completa cantidad y precio' in page.locator('#budget-preview').inner_text())
    page.locator('.budget-examples>summary').click()
    check('Ejemplos de tela, confección y transporte', page.locator('.example-grid article').count() == 3 and page.locator('.example-grid').is_visible())
    page.locator('#id_description').fill('Bordado sin perder el formulario')
    page.locator('#id_unit_price').fill('80')
    category_name = 'Bordado UI '+str(time.time_ns())
    with page.expect_popup() as info:
        page.get_by_role('link', name='Administrar categorías').click()
    settings = info.value
    settings.get_by_role('link', name='Nueva categoría').click()
    settings.get_by_label('Nombre de la categoría').fill(category_name)
    settings.get_by_label('¿Qué gastos incluye?').fill('Logo y aplicaciones de prueba')
    settings.get_by_role('button', name='Guardar registro').click()
    settings.wait_for_url(BASE+'/ajustes/')
    row = settings.locator('.category-settings-row').filter(has_text=category_name)
    code = row.get_attribute('data-category-code')
    check('Categoría personalizada creada desde Ajustes', bool(code) and row.is_visible())
    page.get_by_role('button', name='Actualizar lista').click()
    page.get_by_text('Lista actualizada.', exact=True).wait_for()
    page.locator('#id_category').select_option(code)
    check('Actualizar categorías conserva datos escritos', page.locator('#id_description').input_value() == 'Bordado sin perder el formulario' and page.locator('#id_unit_price').input_value() == '80')
    page.get_by_role('button', name='Guardar registro').click()
    page.wait_for_url('**#presupuesto')
    check('Categoría aparece en presupuesto del modelo', category_name in page.locator('#presupuesto').inner_text())
    page.goto(BASE+'/gastos/nuevo/?modelo='+model_path.strip('/').split('/')[-1])
    page.locator('#id_category').select_option(code)
    page.locator('#id_description').fill('Bordado de prueba')
    page.locator('#id_amount').fill('40')
    page.get_by_role('button', name='Guardar registro').click()
    page.wait_for_url('**#gastos')
    check('Categoría aparece en costo real', category_name in page.locator('#gastos').inner_text())
    page.goto(BASE+'/gastos/?category='+code)
    check('Filtro de costos usa categoría personalizada', category_name in page.locator('table').inner_text() and 'Bordado de prueba' in page.locator('table').inner_text())
    row.get_by_role('button', name='Archivar', exact=True).click()
    settings.wait_for_url(BASE+'/ajustes/')
    page.goto(BASE+budget_path)
    check('Categoría archivada excluida de registros nuevos', page.locator('#id_category option[value="'+code+'"]').count() == 0)
    page.goto(model_url)
    check('Archivar conserva presupuesto y gasto históricos', category_name in page.locator('#presupuesto').inner_text() and category_name in page.locator('#gastos').inner_text())
    budget_row = page.locator('#presupuesto tbody tr').filter(has_text=category_name)
    budget_row.get_by_role('link', name='Editar').click()
    check('Categoría archivada editable en costo anterior', page.locator('#id_category').input_value() == code)
    page.get_by_role('button', name='Guardar registro').click()
    page.wait_for_url('**#presupuesto')
    row.get_by_role('button', name='Reactivar', exact=True).click()
    settings.wait_for_url(BASE+'/ajustes/')
    page.goto(BASE+budget_path)
    check('Categoría reactivada disponible otra vez', page.locator('#id_category option[value="'+code+'"]').count() == 1)
    settings.get_by_label('Tema de la aplicación').last.select_option('light')
    check('Selectores de tema de Ajustes sincronizados', settings.get_by_label('Tema de la aplicación').first.input_value() == 'light')
    page.wait_for_function('document.documentElement.dataset.theme === "light"')
    check('Tema sincronizado entre pestañas', page.locator('html').get_attribute('data-theme') == 'light')
    page.get_by_label('Tema de la aplicación').select_option('system')
    page.emulate_media(color_scheme='dark')
    page.wait_for_function('document.documentElement.dataset.theme === "dark"')
    check('Tema del sistema responde al dispositivo', page.locator('html').get_attribute('data-theme') == 'dark')
    page.emulate_media(color_scheme='light')
    page.wait_for_function('document.documentElement.dataset.theme === "light"')
    check('Tema del sistema cambia a claro', page.locator('html').get_attribute('data-theme') == 'light')
    paths = ['/', '/colecciones/', '/modelos/',model_path,budget_path,'/gastos/','/gastos/nuevo/','/actividad/','/guia/','/ajustes/','/ajustes/categorias/nueva/','/cuenta/contrasena/']
    for theme in ('light','dark'):
        page.set_viewport_size({'width':390,'height':844})
        page.get_by_label('Tema de la aplicación').first.select_option(theme)
        for path in paths:
            page.goto(BASE+path)
            check(f'{theme}: sin desborde móvil {path}', no_overflow(page))
            check(f'{theme}: tema aplicado {path}', page.locator('html').get_attribute('data-theme') == theme)
        page.goto(BASE+budget_path)
        page.locator('.field-info summary').nth(3).click()
        check(f'{theme}: ayuda por toque visible en celular', page.locator('.field-info').nth(3).get_attribute('open') is not None and no_overflow(page))
        page.evaluate("window.scrollTo({top:0, behavior:'instant'})")
        page.screenshot(path=str(OUTPUT/('presupuesto-'+theme+'-movil.png')),full_page=True)
        page.goto(BASE+'/ajustes/')
        page.evaluate("window.scrollTo({top:0, behavior:'instant'})")
        page.screenshot(path=str(OUTPUT/('ajustes-'+theme+'-movil.png')),full_page=True)
    page.set_viewport_size({'width':1440,'height':1000})
    page.goto(BASE+budget_path)
    page.locator('#id_quantity').fill('1.2')
    page.locator('#id_unit').fill('metro')
    page.locator('#id_unit_price').fill('10')
    page.evaluate("window.scrollTo({top:0, behavior:'instant'})")
    page.screenshot(path=str(OUTPUT/'presupuesto-oscuro-desktop.png'),full_page=True)
    page.goto(BASE+'/')
    page.evaluate("window.scrollTo({top:0, behavior:'instant'})")
    page.screenshot(path=str(OUTPUT/'dashboard-oscuro.png'),full_page=True)
    page.locator('.account summary').click()
    page.get_by_role('button', name='Cerrar sesión').click()
    page.wait_for_url('**/ingresar/')
    check('Modo oscuro conservado al salir', page.locator('html').get_attribute('data-theme') == 'dark')
    page.set_viewport_size({'width':390,'height':844})
    check('Login oscuro sin desborde móvil', no_overflow(page))
    check('Sin errores JavaScript', not errors)
    browser.close()
result = {'passed':len(checks), 'checks':checks, 'javascript_errors':errors}
(OUTPUT/'ui-check.json').write_text(json.dumps(result,ensure_ascii=False,indent=2))
print(json.dumps(result,ensure_ascii=False,indent=2))
